-- Real Windows APIs, against buffers owned by THIS offline LuaJIT process.
-- No game process is opened, no protected or executable page is modified.
local ffi=require('ffi')
local runtime=require('bingus_runtime')
local memory=require('bingus_memory').new(runtime)
require('bingus_write').extend(memory)
local buffer=ffi.new('uint8_t[32]')
local pointer=ffi.cast('uint8_t *',buffer)
ffi.copy(buffer,'original bytes',14)
assert(memory.read(pointer,14)=='original bytes')
assert(memory.writable_data(pointer,32))
assert(memory.write(pointer,'checked writer'))
assert(memory.read(pointer,14)=='checked writer')
assert(not memory.writable_data(memory.module(),4),'module image must not be a write target')
local stamp=ffi.new('uintptr_t[1]',ffi.cast('uintptr_t',pointer))
assert(memory.pointer(ffi.string(stamp,8))==pointer)
assert(memory.time()>0)
assert(type(memory.module_hash(memory.module()))=='string','private BCrypt aliases are callable')
print('PASS real Win32 boundary: private FFI aliases, own-buffer read/write, module write refusal, pointer and SHA-256')
